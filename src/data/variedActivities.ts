export const variedActivities: DateActivity[] = groups.flatMap(
  (rows, categoryIndex) =>
    rows.map(([title, description, tags, duration, season], index) => ({
      id: `activity-${321 + categoryIndex * 10 + index}`,
      title,
      description,
      tags: tags.split("|"),
      duration,
      category: dateCategories[categoryIndex]!,
      energy:
        categoryIndex === 2 || categoryIndex === 3 || categoryIndex === 4
          ? "mellan"
          : "låg",
      budget: [322, 324, 345, 348, 364, 368, 370].includes(
        321 + categoryIndex * 10 + index,
      )
        ? "medel"
        : [3, 4].includes(categoryIndex)
          ? "medel"
          : [2, 7].includes(categoryIndex)
            ? "billigt"
            : "gratis",
      season: season?.split("|") as DateActivity["season"],
    })),
);
